#!/usr/bin/env python3
"""AD-189: asset status report (stdlib only).

Scans the repo for the art, font and audio files that export_presets.cfg ships, marks each as
final, placeholder or third-party from tools/asset_status_rules.json, and flags files with no
licence or origin on record. Writes docs/demo/ASSET_STATUS.md. Never edits assets.
Usage: asset_status.py [--root DIR] [--output FILE] [--rules FILE] [--check | --pr-notes]
"""
import argparse
import fnmatch
import json
import os
import sys
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'scripts'))

import audio_check as ac  # noqa: E402

SCHEMA_VERSION = 1
STATUSES = ('final', 'placeholder', 'third-party')
AUDIO_SUFFIXES = ('.wav', '.ogg', '.mp3', '.flac')
FONT_SUFFIXES = ('.ttf', '.otf', '.woff', '.woff2', '.fnt')
ART_SUFFIXES = ('.png', '.webp', '.jpg', '.jpeg', '.svg')
SCAN_SUFFIXES = AUDIO_SUFFIXES + FONT_SUFFIXES + ART_SUFFIXES
SKIP_DIRS = ('.git', '.godot')
FONT_DIR = 'art/export/fnt/'
TYPES = ('art', 'font', 'audio')
GENERATED_LICENCE = 'CC0 (project-original, assets/audio/README.md)'
GENERATED_NOTE = 'generated by scripts/gen_placeholder_audio.py'
UNMATCHED_AUDIO_NOTE = 'not generator output; add a licence rule'
UNMATCHED_NOTE = 'no rule matches; add a rule to tools/asset_status_rules.json'
RECORD_HEADERS = ['file', 'type', 'status', 'licence', 'note']


def export_excludes(cfg):
    """Patterns from the first exclude_filter= line of export_presets.cfg (empty if none)."""
    if not cfg.is_file():
        return []
    for line in cfg.read_text(encoding='utf-8').splitlines():
        if line.startswith('exclude_filter='):
            value = line.split('=', 1)[1].strip().strip('"')
            return [p.strip() for p in value.split(',') if p.strip()]
    return []


def load_rules(path):
    data = json.loads(Path(path).read_text(encoding='utf-8'))
    if data.get('schema_version') != SCHEMA_VERSION:
        raise ValueError('%s: schema_version must be %d' % (path, SCHEMA_VERSION))
    rules = data.get('rules', [])
    for r in rules:
        if not r.get('glob') or r.get('status') not in STATUSES:
            raise ValueError('%s: bad rule %r' % (path, r))
    return rules


def match_rule(rules, rel):
    """First rule whose glob matches the repo-relative posix path, or None."""
    for r in rules:
        if fnmatch.fnmatchcase(rel, r['glob']):
            return r
    return None


def scan(root, excludes):
    """Sorted repo-relative posix paths of shipped art, font and audio files."""
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in filenames:
            path = Path(dirpath) / name
            if path.suffix.lower() not in SCAN_SUFFIXES:
                continue
            rel = path.relative_to(root).as_posix()
            if any(fnmatch.fnmatchcase(rel, pat) for pat in excludes):
                continue
            found.append(rel)
    return sorted(found)


def asset_type(rel):
    suffix = PurePosixPath(rel).suffix.lower()
    if suffix in AUDIO_SUFFIXES:
        return 'audio'
    if rel.startswith(FONT_DIR) or suffix in FONT_SUFFIXES:
        return 'font'
    return 'art'


def load_audio_entries(root):
    """Map repo-relative stream path -> cue entry classified by audio_check (empty if no cue file)."""
    cues = root / 'game' / 'audio' / 'audio_cues_v1.json'
    if not cues.is_file():
        return {}
    entries = ac.build_entries(json.loads(cues.read_text(encoding='utf-8')))
    cache = {}
    for e in entries:
        ac.classify(e, root, cache)
    return {ac.rel(e['stream']): e for e in entries}


def classify_file(rel, root, rules, audio_entries):
    kind = asset_type(rel)
    entry = audio_entries.get(rel) if kind == 'audio' else None
    if entry and entry['status'] == 'placeholder' and (root / rel).is_file():
        status, licence, note = 'placeholder', GENERATED_LICENCE, GENERATED_NOTE
    else:
        rule = match_rule(rules, rel)
        if rule:
            status, licence = rule['status'], rule.get('licence', '')
            note = '; '.join(x for x in (rule.get('credit', ''), rule.get('note', '')) if x)
        elif kind == 'audio':
            status, licence, note = 'third-party', '', UNMATCHED_AUDIO_NOTE
        else:
            status, licence, note = 'unknown', '', UNMATCHED_NOTE
    flagged = status == 'unknown' or (status == 'third-party' and not licence)
    return {'file': rel, 'type': kind, 'status': status, 'licence': licence, 'note': note, 'flagged': flagged}


def build_records(root, rules, excludes):
    audio_entries = load_audio_entries(root)
    return [classify_file(rel, root, rules, audio_entries) for rel in scan(root, excludes)]


def md_table(headers, rows):
    lines = ['| ' + ' | '.join(headers) + ' |', '|' + '---|' * len(headers)]
    lines += ['| ' + ' | '.join(str(c).replace('|', '\\|') for c in r) + ' |' for r in rows]
    return lines


def section_lines(rows, headers):
    return md_table(headers, rows) if rows else ['None']


def summary_lines(records):
    rows = []
    for kind in TYPES + ('total',):
        items = [r for r in records if kind == 'total' or r['type'] == kind]
        rows.append([kind, str(len(items))] + [str(sum(r['status'] == s for r in items)) for s in STATUSES]
                    + [str(sum(r['status'] == 'unknown' for r in items)), str(sum(r['flagged'] for r in items))])
    return ['## Summary', ''] + md_table(['type', 'files', 'final', 'placeholder', 'third-party', 'unknown', 'flagged'],
                                         rows) + ['']


def flagged_lines(records):
    rows = [[r['file'], r['type'], r['status'], r['licence'] or '(none recorded)', r['note']]
            for r in records if r['flagged']]
    return ['## Flagged: needs licence or origin', ''] + section_lines(rows, RECORD_HEADERS) + ['']


def game_art_lines(records):
    dirs = {}
    for r in records:
        if r['type'] == 'audio':
            continue
        d = PurePosixPath(r['file']).parent.as_posix()
        c = dirs.setdefault(d, {'files': 0, 'placeholder': 0, 'final': 0, 'third-party': 0, 'flagged': 0})
        c['files'] += 1
        if r['status'] in STATUSES:
            c[r['status']] += 1
        c['flagged'] += r['flagged']
    rows = [[d, str(c['files']), str(c['placeholder']), str(c['final']), str(c['third-party']), str(c['flagged'])]
            for d, c in sorted(dirs.items())]
    return (['## Game-art list', ''] + section_lines(rows, ['directory', 'files', 'placeholder', 'final',
                                                          'third-party', 'flagged'])
            + ['', 'Missing audio cues are tracked in docs/demo/AUDIO_STATUS.md (AD-188).', ''])


def pr_notes_lines(records):
    return flagged_lines(records) + game_art_lines(records)


def all_files_lines(records):
    rows = [[r['file'], r['type'], r['status'], r['licence'] or '(none recorded)', r['note']] for r in records]
    return ['## All files', ''] + section_lines(rows, RECORD_HEADERS) + ['']


def render(records):
    head = ['# Asset status (AD-189)', '',
            'Regenerate: `python3 tools/asset_status.py` (scans the repo; rules in tools/asset_status_rules.json; '
            'audio classified by scripts/audio_check.py).', '']
    return '\n'.join(head + summary_lines(records) + pr_notes_lines(records) + all_files_lines(records)) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description='AD-189 asset status report')
    ap.add_argument('--root', type=Path, default=ROOT)
    ap.add_argument('--output', type=Path, default=None)
    ap.add_argument('--rules', type=Path, default=None)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='exit 1 if the output differs from a fresh render; write nothing')
    mode.add_argument('--pr-notes', action='store_true', help='print the Flagged and Game-art list sections; write nothing')
    args = ap.parse_args(argv)
    root = args.root.resolve()
    output = args.output or root / 'docs' / 'demo' / 'ASSET_STATUS.md'
    rules_path = args.rules or ROOT / 'tools' / 'asset_status_rules.json'

    try:
        rules = load_rules(rules_path)
    except (OSError, ValueError) as err:
        print('asset_status: %s' % err, file=sys.stderr)
        return 2
    records = build_records(root, rules, export_excludes(root / 'export_presets.cfg'))

    if args.pr_notes:
        sys.stdout.write('\n'.join(pr_notes_lines(records)) + '\n')
        return 0
    text = render(records)
    if args.check:
        current = output.read_bytes().replace(b'\r\n', b'\n') if output.is_file() else None
        if current != text.encode('utf-8'):
            print('%s is out of date; run python3 tools/asset_status.py' % output, file=sys.stderr)
            return 1
        print('%s is up to date' % output)
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    with open(output, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s (%d files, %d flagged)' % (output, len(records), sum(r['flagged'] for r in records)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
