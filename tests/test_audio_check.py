#!/usr/bin/env python3
"""AD-188: tests for scripts/audio_check.py. Local only, stdlib unittest; writes only under temp dirs."""
import contextlib
import io
import json
import math
import struct
import sys
import tempfile
import unittest
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'scripts'))

import audio_check as ac  # noqa: E402
import gen_placeholder_audio as gen  # noqa: E402

MINI_CUES = {
    'unstealable_priority': 3,
    'cues': {
        'sfx.cast.fire': {'stream': 'res://assets/audio/sfx/sfx_cast_fire.wav', 'bus': 'SFX', 'priority': 1},
        'sfx.hit.dummy': {'stream': 'res://assets/audio/sfx/sfx_hit_dummy.wav', 'bus': 'SFX', 'priority': 1},
        'sfx.silent': {'stream': 'res://assets/audio/sfx/sfx_silent.wav', 'bus': 'SFX', 'priority': 1},
        'amb.ruins': {'stream': 'res://assets/audio/amb/amb_ruins.wav', 'bus': 'Ambience', 'priority': 1, 'loop': True},
    },
    'music': {
        'bus': 'Music',
        'contexts': {
            'ruins': {
                'stream': 'res://assets/audio/music/mus_ruins.ogg',
                'placeholder': 'res://assets/audio/amb/amb_ruins.wav',
            },
        },
    },
}

_GENERATED = {}


def generated(cue_id):
    if cue_id not in _GENERATED:
        _GENERATED[cue_id] = gen.wav_bytes(gen.render(cue_id), cue_id.startswith('amb.'))
    return _GENERATED[cue_id]


def shifted(cue_id, index, delta):
    """Generated bytes with one 16-bit sample moved by delta (same length)."""
    data = bytearray(generated(cue_id))
    value = struct.unpack_from('<h', data, 44 + 2 * index)[0]
    if value + delta > 32767:
        delta = -delta
    struct.pack_into('<h', data, 44 + 2 * index, value + delta)
    return bytes(data)


def write_bytes(root, rel, data):
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def write_dummy_wav(path, seconds=0.2, amp=0.5, freq=440.0, rate=44100):
    """Mono 16-bit PCM sine at amp of full scale (amp 0.5 is about -6 dBFS)."""
    n = int(round(seconds * rate))
    samples = [int(round(amp * 32767 * math.sin(2 * math.pi * freq * i / rate))) for i in range(n)]
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(struct.pack('<%dh' % n, *samples))


def section(report, start, end=None):
    i = report.index(start)
    j = report.index(end, i) if end else len(report)
    return report[i:j]


class AudioCheckTest(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.tmp = Path(tmp.name)
        self.root = self.tmp / 'root'
        self.output = self.tmp / 'AUDIO_STATUS.md'
        cue_path = self.root / 'game' / 'audio' / 'audio_cues_v1.json'
        cue_path.parent.mkdir(parents=True)
        cue_path.write_text(json.dumps(MINI_CUES), encoding='utf-8')
        write_bytes(self.root, 'assets/audio/amb/amb_ruins.wav', generated('amb.ruins'))

    def run_main(self, root=None, output=None):
        out = output or self.output
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            rc = ac.main(['--root', str(root or self.root), '--output', str(out)])
        return rc, buf.getvalue(), out.read_text(encoding='utf-8')

    def test_real_repo_lists_every_id(self):
        rc, _, report = self.run_main(root=ac.ROOT, output=self.tmp / 'real.md')
        self.assertEqual(rc, 0)
        cues = json.loads((ac.ROOT / 'game/audio/audio_cues_v1.json').read_text(encoding='utf-8'))
        ids = list(cues['cues']) + ['music.' + c for c in cues['music']['contexts']]
        for cid in ids:
            self.assertIn('| %s |' % cid, report)
        absent = []
        for cid, cfg in cues['cues'].items():
            if not (ac.ROOT / cfg['stream'][len('res://'):]).is_file():
                absent.append(cid)
        for ctx, cfg in cues['music']['contexts'].items():
            if not (ac.ROOT / cfg['stream'][len('res://'):]).is_file():
                absent.append('music.' + ctx)
        self.assertTrue(absent)
        dropped_at = report.index('## Dropped files')
        for cid in absent:
            self.assertLess(report.index('| %s |' % cid), dropped_at)

    def test_missing_music_listed_under_music(self):
        rc, _, report = self.run_main()
        self.assertEqual(rc, 0)
        music = section(report, '### Music', '### Ambience')
        self.assertIn('| music.ruins | assets/audio/music/mus_ruins.ogg | assets/audio/amb/amb_ruins.wav | ogg, 15-300 s, loop |', music)

    def test_generated_amb_is_placeholder(self):
        _, _, report = self.run_main()
        self.assertIn('| amb.ruins | ambience | placeholder |', report)
        self.assertIn('| amb.ruins | assets/audio/amb/amb_ruins.wav | generated placeholder (same file) |',
                      section(report, '### Ambience', '### SFX'))

    def test_off_by_one_sample_is_generated_but_larger_change_is_dropped(self):
        write_bytes(self.root, 'assets/audio/sfx/sfx_cast_fire.wav', shifted('sfx.cast.fire', 1000, 1))
        _, _, report = self.run_main()
        self.assertIn('| sfx.cast.fire | sfx | placeholder |', report)

        write_bytes(self.root, 'assets/audio/sfx/sfx_cast_fire.wav', shifted('sfx.cast.fire', 1000, 500))
        _, _, report = self.run_main()
        self.assertIn('| sfx.cast.fire | sfx | dropped |', report)

    def test_dropped_dummy_wav_passes_checks(self):
        write_dummy_wav(self.root / 'assets/audio/sfx/sfx_hit_dummy.wav')
        rc, stdout, report = self.run_main()
        self.assertEqual(rc, 0)
        self.assertNotIn('problem', stdout)
        self.assertNotIn('| sfx.hit.dummy |', section(report, '### SFX', '## Dropped files'))
        self.assertIn('| sfx.hit.dummy |', section(report, '## Dropped files', '## Unmapped files'))

    def test_loud_dummy_wav_reports_peak_problem(self):
        write_dummy_wav(self.root / 'assets/audio/sfx/sfx_hit_dummy.wav', amp=1.0)
        _, stdout, _ = self.run_main()
        self.assertIn('problem sfx.hit.dummy: peak', stdout)

    def test_silent_cue(self):
        _, _, report = self.run_main()
        self.assertIn('| sfx.silent | sfx | silent |', report)
        self.assertIn('| sfx.silent | assets/audio/sfx/sfx_silent.wav | none (silent) |',
                      section(report, '### SFX', '## Dropped files'))

    def test_wrong_extension_exits_1_with_hint(self):
        write_bytes(self.root, 'assets/audio/music/mus_ruins.mp3', b'not really audio')
        rc, _, report = self.run_main()
        self.assertEqual(rc, 1)
        self.assertIn('| assets/audio/music/mus_ruins.mp3 | runtime loads only assets/audio/music/mus_ruins.ogg |', report)

    def test_two_runs_are_identical(self):
        write_dummy_wav(self.root / 'assets/audio/sfx/sfx_hit_dummy.wav')
        first = self.tmp / 'first.md'
        second = self.tmp / 'second.md'
        rc1, _, _ = self.run_main(output=first)
        rc2, _, _ = self.run_main(output=second)
        self.assertEqual((rc1, rc2), (0, 0))
        self.assertEqual(first.read_bytes(), second.read_bytes())
        self.assertNotIn(b'\r', first.read_bytes())


if __name__ == '__main__':
    unittest.main()
